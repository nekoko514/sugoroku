const ALL = Object.values(SHOWCASE).flat();
const BY_ID = Object.fromEntries(ALL.map((it) => [it.id, it]));

// マスに着いたときに一覧で見せる品物（隠れた品物は出さない）
export function showcaseFor(squareId, { cast = true } = {}) {
  return (SHOWCASE[squareId] || []).filter((it) => !it.hidden && (cast || !it.cast));
}

// その品物を近くで見たことで、奥へ進めるようになる隠れた品物
export function unlockedBy(itemId, { cast = true } = {}) {
  return ALL.filter((it) => it.hidden && it.unlockBy === itemId && (cast || !it.cast));
}

export function findItem(id) {
  return BY_ID[String(id || '').trim()] || null;
}
