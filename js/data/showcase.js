const ALL = Object.values(SHOWCASE).flat();
const BY_ID = Object.fromEntries(ALL.map((it) => [it.id, it]));

export function showcaseFor(squareId, { cast = true } = {}) {
  return (SHOWCASE[squareId] || []).filter((it) => cast || !it.cast);
}

export function findItem(id) {
  return BY_ID[String(id || '').trim()] || null;
}
