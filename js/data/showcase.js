// 施設ごとの「ショーケース」。
//
// マスに着いたとき、ペルソナには name と short（名前と一言）の一覧だけを渡す。
// ペルソナが気になったものを「近くで見る」と、detail（詳しい情報）がユーザーには見えないところで届く。
// 0から想像させずに、手ざわりのある具体的な情報を渡すことで、ペルソナのプロンプトの書き方に左右されずに
// 豊かな描写ができるようにしている。
//
// id    … 半角英数字とハイフン。ほかの品物と重ならないように
// cast  … true のものは、スタッフなどほかの登場人物が出てくる品物（「ほかの登場人物」をオフにすると出さない）
// hidden, unlockBy … 一覧には出さない隠れた品物。unlockBy の品物を近くで見たときに、初めて見られるようになる。
//                    建物や品物の奥にある、誰かの人生の話（裏設定）は、こうして奥へ奥へとたどれるようにしている
//
// 方針: 魔法や不思議は使わない。素材・産地・配合・作り方・歴史・舌ざわりなど、現実にありそうな具体的な情報にする。

