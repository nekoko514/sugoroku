// スタートから何マス進んだかで、園内の時間帯が変わる
export function timeOfDay(step, total) {
  const r = step / (total - 1);
  if (r < 0.25) return '朝';
  if (r < 0.55) return '昼';
  if (r < 0.8) return '夕暮れ';
  return '夜';
}

// そのマスに止まったときに、ペルソナへ手渡す種を選ぶ
export function pickSeeds(square, time, rand = Math.random) {
  const out = [];
  for (const seed of square.seeds) {
    const sd = typeof seed === 'string' ? { text: seed } : seed;
    if (sd.when && !sd.when.includes(time)) continue;
    if (sd.chance != null && rand() >= sd.chance) continue;
    out.push(sd.text);
  }
  return out;
}

