// 進んだマスの位置で、園内の時間帯が変わる
export function timeOfDay(index, total) {
  const r = index / (total - 1);
  if (r < 0.25) return '朝';
  if (r < 0.55) return '昼';
  if (r < 0.8) return '夕暮れ';
  return '夜';
}

