const BY_VIA = Object.fromEntries(SECRETS.map((s) => [s.via, s]));

// 近くで見た品物に、まだ見つけていない隠しアイテムがあれば、確率で見つける
export function trySecret(itemId, { found = [], rand = Math.random } = {}) {
  const s = BY_VIA[itemId];
  if (!s || found.includes(s.id)) return null;
  return rand() < s.chance ? s : null;
}

// そのマスに着いたとき、持っているアイテムがきっかけで起こる出来事
export function linksAt(squareId, found = []) {
  return SECRETS.filter((s) => s.link.at === squareId && found.includes(s.id));
}

export function linkText(secret, cast) {
  return (!cast && secret.link.textNoCast) || secret.link.text;
}

export function secretById(id) {
  return SECRETS.find((s) => s.id === id) || null;
}
