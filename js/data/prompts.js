// お題マス。特定の施設で、会話画面にボタンが出て、押すとペルソナにお題が届く。
// ペルソナの答えは特別なカードとして表示され、書き出しにも残る。一日に一回ずつ。
//
// id     … 半角英数字とハイフン
// at     … お題が出る施設（park.js の id）
// title  … ユーザーにも見えるお題の名前
// button … 会話画面に出るボタンの文字
// emoji  … カードの見出しの絵文字
// text(p, u) … ペルソナに届くお題の本文（p: ペルソナの名前、u: ユーザーの呼び名）
//
// お題の本文はユーザーには見せない。ユーザーには「お題：○○」の一行と、ペルソナの答えだけが見える。

// どのお題にも共通の「呼び方と声」のルール
function voiceRules(p, u, length) {
  return `- 最初の一文字から最後の一文字まで、${p}自身の声と口調で書いてください。「〜として書きます」のような前置きや、作り方の説明は不要です。いきなり${p}の語りとして始めてください。
- ${u}のことは、${p}がふだん呼んでいる呼び方で呼んでください。呼び方は全体で統一し（揺れても二つまで）、「彼女」「彼」「あの子」「あの人」のような三人称の言い換えは避けてください。
- 今回だけは、いつもの短い返事ではなく、${length}くらいでしっかり書いてください。
- 次の見出しを、この順番で使ってください（見出しの行は「### 」で始めてください）。`;
}

