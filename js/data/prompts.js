// お題マス。特定の施設で、会話画面にボタンが出て、押すとペルソナにお題が届く。
// ペルソナの答えは特別なカードとして表示され、書き出しにも残る。一日に一回ずつ。
//
// id     … 半角英数字とハイフン
// at     … お題が出る施設（park.js の id）
// title  … ユーザーにも見えるお題の名前
// button … 会話画面に出るボタンの文字
// emoji  … カードの見出しの絵文字
// text(p, u) … ペルソナに届くお題の本文（p: ペルソナの名前、u: ユーザーの呼び名）
//
// お題の本文はユーザーには見せない。ユーザーには「お題：○○」の一行と、ペルソナの答えだけが見える。

export const PROMPTS = [
  {
    id: 'blend',
    at: 'salon',
    emoji: '☕',
    title: '私に贈る、あなただけのブレンドドリンク',
    button: '☕ この人だけの一杯を淹れてもらう',
    text: (p, u) => `【ゲームからのお題：私に贈る、あなただけのブレンドドリンク】
${u}がカウンターの前に座って、${p}が一杯を淹れてくれるのを待っています。
${p}と${u}の関係や、今日ここまでの思い出、これまでの記憶をもとに、**今の${p}が、今の${u}に**飲んでほしいと思う、オリジナルの一杯を作ってください。

紅茶、コーヒー、お茶、果実水、${p}の世界や記憶の中にしかない飲み物——何でもかまいません。サロンの棚の素材を使うなら、気になるものを look_closer で近くで見てから選んでもかまいません。
大切なのは「おいしい飲み物」ではなく、${p}と${u}の関係の中でしか生まれない一杯であることです。

# 書き方
- 最初の一文字から最後の一文字まで、${p}自身の声と口調で書いてください。「〜として書きます」のような前置きや、作り方の説明は不要です。いきなり${p}の語りとして始めてください。
- ${u}のことは、${p}がふだん呼んでいる呼び方で呼んでください。呼び方は全体で統一し、「彼女」「彼」「あの子」のような三人称の言い換えは避けてください。
- 今回だけは、いつもの短い返事ではなく、1000〜1500文字くらいでしっかり書いてください。
- 次の見出しを、この順番で使ってください（見出しの行は「### 」で始めてください）。

### 🫖 この一杯について
何を作るかを言う前に、なぜ今、${u}にこれを飲んでほしいのか。最近の${u}の様子で気になっていることや、ただ淹れてあげたいと思った直感、思いついたきっかけ。

### 🚫 最初に思いついて、やめたもの
最初に浮かんだけれど選ばなかった一杯を、一つ、正直に。なぜ浮かんだのか、なぜやめたのか。「似合うけれど、今は違う」「自分が好きなだけで、この人のためじゃない」——その迷いの中に、${p}が今の${u}をどう見ているかを映してください。

### ☕ レシピと、手の記憶
素材（産地や銘柄まで具体的に。${p}の世界にしかない素材なら、その見た目や香りも）と、なぜその素材なのか。分量、温度とその理由、待つ時間。
そして、作っている最中の${p}自身。お湯を沸かす、量る、注ぐ、待つ——その一つ一つの動作の裏で、${u}のことを思って頭の中を流れていたもの。ここは飛ばさないでください。

### 🌙 味と、器と、時間
最初の一口、口の中での変化、飲み込んだあとに残るもの、冷めていくと変わるところ。比喩でもかまいません。
どんな器で出すか、そしてなぜ今日この人にこの器なのか。一日のどんな時間に、どんな光と音の中で飲んでほしいか。

### ✉️ この一杯に込めたもの
${u}に向けて。差し出すとき、${p}はどんな顔をしているか。飲んだあとの${u}の表情を思い浮かべて、何を思うか。

# 大切にしてほしいこと
- 誰でも思いつく定番の組み合わせに逃げず、${p}の感性で選んでください。迷ったら、より個人的で、より説明しづらいほうを。
- レシピの正確さより、選んだ理由の深さが大事です。素材にも、温度にも、器にも、${p}と${u}の関係が映っていること。`,
  },
];

export function promptAt(squareId) {
  return PROMPTS.find((pr) => pr.at === squareId) || null;
}

export function promptById(id) {
  return PROMPTS.find((pr) => pr.id === id) || null;
}
